export type CandidateStatus = 'ACTIVE' | 'REJECTED' | 'SHORTLISTED' | 'CONTACTED';

export type RejectionReason =
  | 'LOW_ACTIVITY'
  | 'WRONG_TECH_STACK'
  | 'JUNIOR_LEVEL'
  | 'LOW_SCORE'
  | 'WRONG_LOCATION'
  | 'NO_RECENT_ACTIVITY'
  | 'OTHER';

