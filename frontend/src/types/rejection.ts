  LOW_ACTIVITY: '활동량 부족',
  WRONG_TECH_STACK: '기술 스택 불일치',
  JUNIOR_LEVEL: '경력 수준 부족',
  LOW_SCORE: '점수 낮음',
  WRONG_LOCATION: '위치 부적합',
  NO_RECENT_ACTIVITY: '최근 활동 없음',
  OTHER: '기타',
